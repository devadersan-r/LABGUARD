"""Secret-key generation and management for LABGUARD.

Implements cryptographically random key generation, POSIX permission enforcement (0600),
atomic file writes, key-ID-specific resolution (failing closed for unknown key IDs),
and ESP32 C++ header export.

Conforms to Section 7 of authenticator.txt and Section 3 of correction.txt.
"""

from __future__ import annotations

import base64
import json
import os
import re
import secrets
import stat
import sys
import tempfile
from datetime import datetime, timezone
from pathlib import Path
from typing import Any, Dict, Optional, Union

from labguard.crypto import InvalidKeyError, decode_key

DEFAULT_KEY_ID = "KEY-001"
SUPPORTED_ALGORITHM = "HMAC-SHA256"
KEY_ID_REGEX = re.compile(r"^[A-Za-z0-9_\-\.]{1,32}$")


class KeyManagerError(Exception):
    """Base exception for key management errors."""
    pass


class KeyNotFoundError(KeyManagerError):
    """Raised when a requested key identifier is not found in the key store."""
    pass


class KeyStoreCorruptedError(KeyManagerError):
    """Raised when an existing key store file cannot be parsed, validated, or is corrupt."""
    pass


class UnsupportedAlgorithmError(KeyManagerError):
    """Raised when a key entry specifies an unsupported cryptographic algorithm."""
    pass


def validate_key_id(key_id: str) -> str:
    """Validate a non-secret key identifier.

    Args:
        key_id: Alphanumeric identifier, e.g., 'KEY-001'.

    Returns:
        The validated key_id string.

    Raises:
        KeyManagerError: If key_id is invalid or malformed.
    """
    if not isinstance(key_id, str) or not key_id.strip():
        raise KeyManagerError("Key identifier must be a non-empty string")
    cleaned = key_id.strip()
    if not KEY_ID_REGEX.match(cleaned):
        raise KeyManagerError(
            f"Invalid key identifier '{cleaned}': must be 1-32 alphanumeric characters, "
            "hyphens, dots, or underscores"
        )
    return cleaned


def generate_secret_key(
    key_id: str = DEFAULT_KEY_ID,
    description: str = "",
) -> Dict[str, Any]:
    """Generate a fresh 32-byte cryptographically secure random key.

    Uses Python's secrets module (os.urandom backed by CSPRNG).

    Args:
        key_id: Non-secret identifier for the key (default 'KEY-001').
        description: Optional human-readable description.

    Returns:
        Dictionary containing key metadata and both hex and base64 representations.
    """
    valid_id = validate_key_id(key_id)
    raw_key = secrets.token_bytes(32)
    hex_key = raw_key.hex().lower()
    b64_key = base64.b64encode(raw_key).decode("ascii")

    return {
        "key_id": valid_id,
        "algorithm": SUPPORTED_ALGORITHM,
        "length_bytes": 32,
        "key_hex": hex_key,
        "key_b64": b64_key,
        "created_at": datetime.now(timezone.utc).isoformat(),
        "description": description or f"LABGUARD key for {valid_id}",
    }


def format_esp32_header(key_bytes: bytes, key_id: str) -> str:
    """Format key into C++ header code for Arduino ESP32 DevKit firmware.

    Args:
        key_bytes: Raw 32-byte secret key.
        key_id: Non-secret key identifier.

    Returns:
        C++ header source code containing byte array and key id.
    """
    valid_id = validate_key_id(key_id)
    if len(key_bytes) != 32:
        raise InvalidKeyError(f"Expected 32-byte key, got {len(key_bytes)} bytes")

    # Format bytes in rows of 8 hex constants
    hex_rows = []
    for i in range(0, 32, 8):
        chunk = key_bytes[i : i + 8]
        hex_row = ", ".join(f"0x{b:02X}" for b in chunk)
        hex_rows.append(f"    {hex_row}")
    formatted_array = ",\n".join(hex_rows)

    return f"""// Auto-generated by LABGUARD Key Management System
// DO NOT COMMIT THIS FILE TO VERSION CONTROL
#ifndef LABGUARD_SECRETS_H
#define LABGUARD_SECRETS_H

#include <Arduino.h>

// =============================================================================
// LABGUARD AUTHENTICATION KEY CONFIGURATION
// =============================================================================
// Security Note:
// Storing software keys in microcontroller flash memory is intended for
// development, prototypes, and controlled test environments. A key in flash can
// potentially be extracted via physical access, JTAG, or direct flash dump.
// For production deployments, integrate a hardware secure element (e.g., ATECC608A)
// or enable ESP32 Flash Encryption and Secure Boot v2.
// =============================================================================

static const char* const LABGUARD_KEY_ID = "{valid_id}";

static const uint8_t LABGUARD_SECRET_KEY[32] = {{
{formatted_array}
}};

#endif // LABGUARD_SECRETS_H
"""


class KeyStore:
    """Manages local secret keys, file permissions, and environment variable fallbacks.

    Hardened security properties:
    - Enforces POSIX file permissions (0600: read/write by owner only).
    - Uses atomic file writes (via temporary file and atomic rename).
    - Validates algorithm is strictly HMAC-SHA256.
    - Matches entry key_id with mapping key_id.
    - Strict key-ID-specific resolution: fails closed for unknown key IDs.
      (Generic fallback variables like LABGUARD_SECRET_KEY are removed).
    - Never silently discards corrupt keystore files.
    - Never prints or logs secret keys.
    """

    def __init__(self, key_store_path: Optional[Union[str, Path]] = None) -> None:
        """Initialize KeyStore.

        Args:
            key_store_path: Optional path to JSON key store file.
        """
        self._keys: Dict[str, bytes] = {}
        self._metadata: Dict[str, Dict[str, Any]] = {}
        self.key_store_path: Optional[Path] = Path(key_store_path) if key_store_path else None

        if self.key_store_path and self.key_store_path.exists():
            self.load_from_file(self.key_store_path)

    def add_key(
        self,
        key_id: str,
        secret_key: Union[str, bytes],
        description: str = "",
        algorithm: str = SUPPORTED_ALGORITHM,
        overwrite: bool = False,
    ) -> None:
        """Add or register a key in the in-memory store.

        Args:
            key_id: Key identifier (e.g. 'KEY-001').
            secret_key: Raw bytes, hex string (64 chars), or base64 string.
            description: Optional descriptive text.
            algorithm: Must be 'HMAC-SHA256'.
            overwrite: If False, raises error if key_id already exists.

        Raises:
            KeyManagerError: If key_id already exists and overwrite is False.
            UnsupportedAlgorithmError: If algorithm is not HMAC-SHA256.
            InvalidKeyError: If key is invalid.
        """
        valid_id = validate_key_id(key_id)

        if algorithm != SUPPORTED_ALGORITHM:
            raise UnsupportedAlgorithmError(
                f"Unsupported algorithm '{algorithm}': only '{SUPPORTED_ALGORITHM}' is supported"
            )

        if valid_id in self._keys and not overwrite:
            raise KeyManagerError(f"Key identifier '{valid_id}' already exists in keystore")

        key_bytes = decode_key(secret_key)
        self._keys[valid_id] = key_bytes
        self._metadata[valid_id] = {
            "key_id": valid_id,
            "algorithm": SUPPORTED_ALGORITHM,
            "length_bytes": 32,
            "created_at": datetime.now(timezone.utc).isoformat(),
            "description": description or f"Key for {valid_id}",
        }

    def has_key(self, key_id: str) -> bool:
        """Check if a key is available in store or via explicit key-specific environment variable."""
        try:
            valid_id = validate_key_id(key_id)
        except KeyManagerError:
            return False

        if valid_id in self._keys:
            return True

        # Check key-specific environment variable ONLY (e.g., LABGUARD_KEY_KEY_001)
        env_var_specific = f"LABGUARD_KEY_{valid_id.replace('-', '_').replace('.', '_')}"
        if env_var_specific in os.environ:
            return True

        # Note: Generic fallback LABGUARD_SECRET_KEY is removed to fail closed.
        return False

    def get_key(self, key_id: str) -> bytes:
        """Retrieve a validated 32-byte secret key by key_id.

        Checks:
            1. In-memory keystore / loaded key file.
            2. Specific environment variable: LABGUARD_KEY_<KEY_ID>.

        FAILS CLOSED: Never falls back to a generic secret key for an unknown key_id.

        Args:
            key_id: Key identifier (e.g. 'KEY-001').

        Returns:
            32-byte secret key.

        Raises:
            KeyNotFoundError: If key cannot be found.
            InvalidKeyError: If found key is malformed.
        """
        valid_id = validate_key_id(key_id)

        # 1. Check in-memory store
        if valid_id in self._keys:
            return self._keys[valid_id]

        # 2. Check key-specific environment variable
        env_key_name = f"LABGUARD_KEY_{valid_id.replace('-', '_').replace('.', '_')}"
        env_val = os.environ.get(env_key_name)
        if env_val:
            try:
                decoded = decode_key(env_val)
                self._keys[valid_id] = decoded
                return decoded
            except InvalidKeyError as err:
                raise InvalidKeyError(
                    f"Environment variable '{env_key_name}' contains an invalid key: {err}"
                ) from err

        # Fails closed
        raise KeyNotFoundError(
            f"Key identifier '{valid_id}' not found in key store or environment variables"
        )

    def list_key_ids(self) -> list[str]:
        """List registered key identifiers without exposing key contents."""
        return sorted(list(self._keys.keys()))

    def save_to_file(self, target_path: Union[str, Path]) -> Path:
        """Save keys to a JSON file atomically with restrictive POSIX permissions (0600).

        Uses atomic write via temporary file in the same directory and atomic rename
        (os.replace) to prevent partially written or corrupt files on crash/interruption.

        Args:
            target_path: Destination path.

        Returns:
            Resolved Path of the saved file.
        """
        path = Path(target_path).resolve()
        path.parent.mkdir(parents=True, exist_ok=True)

        payload = {
            "_header": {
                "system": "LABGUARD Key Store",
                "version": "1.0",
                "warning": "CONFIDENTIAL: Do not commit or share this file",
            },
            "keys": {},
        }

        for k_id, k_bytes in self._keys.items():
            meta = self._metadata.get(k_id, {})
            payload["keys"][k_id] = {
                "key_id": k_id,
                "algorithm": SUPPORTED_ALGORITHM,
                "key_hex": k_bytes.hex().lower(),
                "created_at": meta.get("created_at", datetime.now(timezone.utc).isoformat()),
                "description": meta.get("description", ""),
            }

        data_str = json.dumps(payload, indent=2)

        # Atomic write: write to temp file in same directory, set 0600, then replace
        temp_file = tempfile.NamedTemporaryFile(
            mode="w",
            dir=str(path.parent),
            prefix=".keystore_",
            suffix=".tmp",
            delete=False,
            encoding="utf-8",
        )
        temp_path = Path(temp_file.name)
        try:
            temp_file.write(data_str)
            temp_file.flush()
            os.fsync(temp_file.fileno())
            temp_file.close()

            if os.name == "posix":
                os.chmod(temp_path, 0o600)

            # Atomic replace
            os.replace(temp_path, path)

            # Re-ensure 0600 on final destination
            if os.name == "posix":
                os.chmod(path, 0o600)
        except Exception:
            if temp_path.exists():
                try:
                    temp_path.unlink()
                except OSError:
                    pass
            raise

        self.key_store_path = path
        return path

    def load_from_file(self, source_path: Union[str, Path]) -> None:
        """Load and validate keys from a JSON file.

        Enforces structure validation, algorithm checking, and POSIX permissions.
        FAILS SAFELY: Raises KeyStoreCorruptedError rather than discarding or ignoring corrupt data.

        Args:
            source_path: Path to key store JSON file.

        Raises:
            KeyManagerError: If file is missing or permissions error.
            KeyStoreCorruptedError: If file is malformed, invalid JSON, or invalid schema.
        """
        path = Path(source_path).resolve()
        if not path.exists():
            raise KeyManagerError(f"Key store file not found: {path}")

        # Permission check on POSIX systems
        if os.name == "posix":
            file_stat = path.stat()
            file_mode = stat.S_IMODE(file_stat.st_mode)
            if file_mode & (stat.S_IRWXG | stat.S_IRWXO):
                sys.stderr.write(
                    f"[LABGUARD SECURITY WARNING] Key store file {path} has overly permissive "
                    f"permissions ({oct(file_mode)}). Expected 0600 (owner read/write only).\n"
                )

        try:
            with open(path, "r", encoding="utf-8") as f:
                data = json.load(f)
        except Exception as err:
            raise KeyStoreCorruptedError(
                f"Failed to parse key store JSON file '{path}': {err}"
            ) from err

        if not isinstance(data, dict) or "keys" not in data or not isinstance(data["keys"], dict):
            raise KeyStoreCorruptedError(
                f"Malformed key store format in '{path}': missing top-level 'keys' object"
            )

        new_keys: Dict[str, bytes] = {}
        new_meta: Dict[str, Dict[str, Any]] = {}

        for k_id, k_info in data["keys"].items():
            if not isinstance(k_info, dict) or "key_hex" not in k_info:
                raise KeyStoreCorruptedError(
                    f"Malformed key entry for key_id '{k_id}' in '{path}'"
                )

            valid_id = validate_key_id(k_id)

            # Validate key_id stored matches dict key
            stored_key_id = k_info.get("key_id", valid_id)
            if stored_key_id != valid_id:
                raise KeyStoreCorruptedError(
                    f"Key ID mismatch in entry: dictionary key '{valid_id}' != "
                    f"stored key_id '{stored_key_id}'"
                )

            # Validate algorithm
            algo = k_info.get("algorithm", SUPPORTED_ALGORITHM)
            if algo != SUPPORTED_ALGORITHM:
                raise UnsupportedAlgorithmError(
                    f"Unsupported algorithm '{algo}' for key '{valid_id}': "
                    f"only '{SUPPORTED_ALGORITHM}' is supported"
                )

            # Validate 32-byte key hex
            try:
                k_bytes = decode_key(k_info["key_hex"])
            except InvalidKeyError as err:
                raise KeyStoreCorruptedError(
                    f"Invalid key material for key_id '{valid_id}': {err}"
                ) from err

            new_keys[valid_id] = k_bytes
            new_meta[valid_id] = {
                "key_id": valid_id,
                "algorithm": algo,
                "created_at": k_info.get("created_at"),
                "description": k_info.get("description", ""),
            }

        # Atomically apply validated keys to state
        self._keys.update(new_keys)
        self._metadata.update(new_meta)
        self.key_store_path = path
